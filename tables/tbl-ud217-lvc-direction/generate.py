"""Head direction of compound:lvc arcs in hash-verified official UD 2.17 files.
Usage: python generate.py /path/to/ud217-official
All splits of each Turkic treebank are pooled (the relation is an annotation
convention, not a test statistic). Only integer-ID syntactic words are read.
For each compound:lvc arc the script records the UPOS of dependent and head and
whether the dependent precedes its head. "Verb heads" = the head has UPOS VERB
or AUX; "nominal heads" = any other head UPOS. No parser is run.
Without an argument the table is redrawn from the frozen data.csv.
"""
from pathlib import Path
import argparse,collections,csv,hashlib,json
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]

def words(path):
    sent=[]
    for line in path.read_text(encoding='utf-8').splitlines()+['']:
        if not line.strip():
            if sent: yield sent
            sent=[]
        elif not line.startswith('#'):
            c=line.split('\t')
            if len(c)!=10: raise ValueError(f'invalid row in {path}')
            if c[0].isdigit(): sent.append(c)

def count(paths):
    n=collections.Counter()
    for p in paths:
        for s in words(p):
            for c in s:
                if not c[7].startswith('compound:lvc'): continue
                h=s[int(c[6])-1]
                verb_head=h[3] in {'VERB','AUX'}
                n['arcs']+=1
                n['verb_head' if verb_head else 'nominal_head']+=1
                n['dep_before_head']+=int(c[0])<int(c[6])
    return n

def main():
    ap=argparse.ArgumentParser();ap.add_argument('source_root',type=Path,nargs='?');a=ap.parse_args()
    fields=['treebank','files','arcs','verb_head','nominal_head','dep_before_head','source']
    if a.source_root is None:
        rows=[{k:(int(v) if k in fields[1:6] else v) for k,v in r.items()} for r in csv.DictReader((HERE/'data.csv').open(encoding='utf-8'))]
    else:
        man=json.loads((ROOT/'tables/tbl-ud217-inventory/download-manifest.json').read_text())
        by_tb=collections.defaultdict(list)
        for r in man:
            if 'sha256' not in r: continue
            p=a.source_root/r['file']
            assert hashlib.sha256(p.read_bytes()).hexdigest()==r['sha256'], r['file']
            by_tb[r['file'].split('/')[0]].append((p,r))
        rows=[]
        for tb,items in sorted(by_tb.items()):
            n=count([p for p,_ in items])
            src='; '.join(f"{r['url']} sha256:{r['sha256']}" for _,r in sorted(items,key=lambda x:x[1]['file']))
            rows.append({'treebank':tb,'files':len(items),'arcs':n['arcs'],'verb_head':n['verb_head'],
                         'nominal_head':n['nominal_head'],'dep_before_head':n['dep_before_head'],'source':src})
        with (HERE/'data.csv').open('w',encoding='utf-8',newline='') as f:
            w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)
    lines=['| Treebank (all splits) | `compound:lvc` arcs | Verb/AUX head | Nominal head | Dependent before head |','|:--|--:|--:|--:|--:|']
    for r in rows:
        if r['arcs']==0: continue
        lines.append(f"| {r['treebank'][3:].replace('_', ' ')} | {r['arcs']:,} | {r['verb_head']:,} | {r['nominal_head']:,} | {r['dep_before_head']:,} |")
    lines+=['',': Head direction of `compound:lvc` in the official UD 2.17 Turkic treebanks (all splits pooled; treebanks with no such arc omitted). "Nominal head" means any head whose UPOS is not VERB or AUX, so the light verb depends on the noun or adjective. Counts are an annotation-convention diagnostic, not a parser result. Generated by `tables/tbl-ud217-lvc-direction/generate.py` from hash-verified release files; URLs and hashes are in `data.csv`. {#tbl-lvc-direction}']
    (HERE/'output.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(len(rows),'treebanks;',sum(r['arcs'] for r in rows),'compound:lvc arcs')
if __name__=='__main__':main()
